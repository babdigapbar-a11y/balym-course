export function firebaseErrorKk(err) {
  const code = err?.code || "";
  if (t.firebaseErrors[code]) return t.firebaseErrors[code];
  const short = code.replace(/^auth\//, "");
  if (t.firebaseErrors[`auth/${short}`]) return t.firebaseErrors[`auth/${short}`];
  if (err?.message && /insufficient permissions/i.test(err.message)) {
    return t.firebaseErrors["permission-denied"];
  }
  return err?.message ? String(err.message) : "Белгісіз қате";
}
